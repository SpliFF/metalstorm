#!/usr/bin/env python3
"""Generate mapdata/civilians.lua from meridian_layout.json.

Part of Meridian Basin map generator (PLAN-metalstorm-beta-map.md task 3c).
Reads civilian_districts + convoy_routes from meridian_layout.json and emits
the Lua data file that LuaRules/Gadgets/civilians/spawn.lua expects.

Usage:
    python3 tools/mapgen/civilians_gen.py [--out FILE]
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
LAYOUT_PATH = os.path.join(HERE, "meridian_layout.json")
DEFAULT_OUT = os.path.join(REPO_ROOT, "content", "maps", "meridian_basin", "mapdata", "civilians.lua")

def format_lua_table(data, indent=0):
    """Recursively format a Python dict/list as a Lua table string."""
    ind = "    " * indent
    if isinstance(data, dict):
        lines = ["{"]
        for k, v in data.items():
            key_str = f"[{repr(k)}]" if isinstance(k, int) else k
            val_str = format_lua_table(v, indent + 1)
            lines.append(f"{ind}    {key_str} = {val_str},")
        lines.append(f"{ind}}}")
        return "\n".join(lines)
    elif isinstance(data, list):
        if not data:
            return "{}"
        lines = ["{"]
        for item in data:
            val_str = format_lua_table(item, indent + 1)
            lines.append(f"{ind}    {val_str},")
        lines.append(f"{ind}}}")
        return "\n".join(lines)
    elif isinstance(data, str):
        return repr(data)
    elif isinstance(data, bool):
        return "true" if data else "false"
    elif data is None:
        return "nil"
    else:
        return str(data)

def build_civilians_lua(layout):
    """Civilian sites + convoys as Lua text, and the count line's numbers.

    Layout-only, like the region contract — no seed and no terrain — so
    `meridian2.py` emits the same bytes into a variant package
    (PLAN-maps M9h). Returns `(lua_text, n_sites, n_convoys)`.
    """
    # Extract civilian districts and convoy routes
    civilian_district_keys = layout.get("civilian_districts", [])
    convoy_routes = layout.get("convoy_routes", [])

    # Build region lookup
    regions_by_key = {r["key"]: r for r in layout.get("regions", [])}

    # Build sites from civilian_districts
    sites = []
    for district_key in civilian_district_keys:
        region = regions_by_key.get(district_key)
        if not region:
            print(f"Warning: civilian district '{district_key}' not found in regions", file=sys.stderr)
            continue

        centroid = region.get("centroid", {})
        tags = region.get("tags", [])

        # Determine kind from tags
        kind = "habitat" if "habitat" in tags else "transit"

        site = {
            "key": district_key,
            "region": district_key,
            "kind": kind,
            "pos": {"x": centroid.get("x", 0), "z": centroid.get("z", 0)},
            "population": 20,  # Default population per district
            "defPool": ["civ_person", "civ_vehicle"],  # Default civilian unit types
        }
        sites.append(site)

    # Build convoys from convoy_routes
    convoys = []
    for route in convoy_routes:
        convoy = {
            "id": route.get("id", ""),
            "side": route.get("side", ""),
            "from": route.get("from", ""),
            "to": route.get("to", ""),
            "via": route.get("via", []),
            "waypoints": route.get("waypoints", []),
            "defName": "civ_truck",  # Default convoy vehicle
            "intervalSec": 180,  # 3 minutes between convoys
        }
        convoys.append(convoy)

    # Build the final Lua data structure
    civilians_data = {
        "version": 1,
        "sites": sites,
        "convoys": convoys,
    }

    # Generate Lua code
    lua_code = f"""-- civilians.lua — Meridian Basin civilian placement data
-- Generated by tools/mapgen/civilians_gen.py from meridian_layout.json
-- (PLAN-metalstorm-beta-map.md task 3c)
--
-- Consumed by LuaRules/Gadgets/civilians/spawn.lua:seed(). See spawn.lua
-- for the schema (version, sites, convoys).

return {format_lua_table(civilians_data)}
"""
    return lua_code, len(sites), len(convoys)


def main():
    parser = argparse.ArgumentParser(description="Generate civilians.lua from meridian_layout.json")
    parser.add_argument("--out", default=DEFAULT_OUT, help="Output path (default: %(default)s)")
    args = parser.parse_args()

    # Read the layout JSON
    with open(LAYOUT_PATH, "r") as f:
        layout = json.load(f)

    lua_code, n_sites, n_convoys = build_civilians_lua(layout)

    # Write to output file
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as f:
        f.write(lua_code)

    print(f"Generated {args.out}")
    print(f"  {n_sites} civilian sites (districts)")
    print(f"  {n_convoys} convoy routes")

if __name__ == "__main__":
    main()
