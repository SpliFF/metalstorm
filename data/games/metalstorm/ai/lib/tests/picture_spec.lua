-- lib/tests/picture_spec.lua — the Picture against the fake engine.
-- Run from data/games/metalstorm/ai.
package.path = './?.lua;' .. package.path

local Picture = require('lib.picture')
local FE      = require('lib.testing.fake_engine')
local Fix     = require('lib.tests.fixtures.graph')

describe("lib.picture", function()
    local fe
    before_each(function()
        fe = FE.new({ teamId = 0, playerId = 7, regions = Fix.regionsJson(),
                      power = Fix.powerJson(), pool = 500 }):install()
        fe:setRulesParam('game', 'region_north_ridge_team', 0)
        fe:setRulesParam('game', 'region_central_basin_team', -1)
        fe:setRulesParam('team', 'authority_pool', 120)
        fe:setRulesParam('team', 'team_active_humans', 0)
    end)
    after_each(function() FE.uninstall() end)

    it("loads static data once and overlays live ownership", function()
        local pic = Picture.new({})
        local p = pic:refresh(150)
        assert.are.equal(3, (function() local n = 0; for _ in pairs(p.regions) do n = n + 1 end; return n end)())
        assert.are.equal(0, p.regions.north_ridge.owner)
        assert.are.equal(-1, p.regions.central_basin.owner)
        assert.are.equal(1200, p.power[101].hp)
        assert.are.equal(0, p.teamId); assert.are.equal(7, p.playerId)
        assert.are.equal(2048, p.mapWidth)
        local again = pic:refresh(300)
        assert.are.equal(p.regions, again.regions, 'static geometry table identity is stable')
    end)

    it("buckets own force by region with both scales and idle counts", function()
        fe:setOwnUnits({
            { id = 1, defId = 101, x = 100, z = 100, health = 1.0, hasCommands = false },
            { id = 2, defId = 101, x = 110, z = 100, health = 0.5, hasCommands = true },
            { id = 3, defId = 103, x = 1500, z = 500, health = 1.0, hasCommands = false },
        })
        local p = Picture.new({}):refresh(150)
        local nr = p.ledger.north_ridge
        assert.are.equal(1.5, nr.strength)
        assert.are.equal(1800, nr.health)
        assert.are.equal(2, nr.count); assert.are.equal(1, nr.idle)
        assert.are.equal(1.5, nr.byClass.tanks)
        assert.are.same({ 1, 2 }, nr.units)
        assert.are.equal(3000, p.ledger.central_basin.health)
        local t = Picture.totals(p)
        assert.are.equal(2.5, t.strength); assert.are.equal(3, t.count); assert.are.equal(2, t.idle)
    end)

    it("prices unknown defs at a nominal hp and warns once", function()
        fe:setOwnUnits({ { id = 1, defId = 999, x = 100, z = 100, health = 1.0 } })
        local pic = Picture.new({})
        pic:refresh(150); pic:refresh(300)
        assert.are.equal(1000, pic:refresh(450).ledger.north_ridge.health)
        local warns = 0
        for _, l in ipairs(fe.log) do if l:find('AI%-STANDIN') then warns = warns + 1 end end
        assert.are.equal(1, warns)
    end)

    it("reads the economy from the published pools", function()
        local p = Picture.new({}):refresh(150)
        assert.are.equal(500, p.economy.ownPool)
        assert.are.equal(120, p.economy.teamPool)
        assert.are.equal(1.0, p.economy.costScale)
        assert.are.equal(0, p.economy.humans)
    end)

    it("reads the objective board off the high-water mark, skipping dead ids", function()
        fe:setRulesParam('game', 'objective_count', 3)
        fe:setRulesParam('game', 'objective_1_type', 'control')
        fe:setRulesParam('game', 'objective_1_state', 'active')
        fe:setRulesParam('game', 'objective_1_reward', 110)
        fe:setRulesParam('game', 'objective_1_region', 'central_basin')
        fe:setRulesParam('game', 'objective_1_team', -1)
        fe:setRulesParam('game', 'objective_3_type', 'protect')
        fe:setRulesParam('game', 'objective_3_state', 'active')
        fe:setRulesParam('game', 'objective_3_x', 100)
        fe:setRulesParam('game', 'objective_3_z', 200)
        fe:setRulesParam('game', 'objective_3_r', 50)
        local p = Picture.new({}):refresh(150)
        assert.are.equal('control', p.board[1].type)
        assert.are.equal(110, p.board[1].reward)
        assert.is_nil(p.board[2])
        assert.are.same({ x = 100, z = 200, r = 50 }, p.board[3].pos)
    end)

    it("decays intel honestly and folds radar blips in at low confidence", function()
        local pic = Picture.new({})
        fe:setEnemies({ { id = 9, defId = 101, x = 1500, z = 500, health = 1.0 },
                        { id = 10, defId = 101, x = 1510, z = 500, health = 1.0 } })
        local p = pic:refresh(150)
        assert.are.equal(2, p.intel.central_basin.strength)
        assert.are.equal(1.0, p.intel.central_basin.confidence)
        assert.are.equal(2, p.intel.central_basin.count)
        -- re-sighting REPLACES, never compounds
        p = pic:refresh(160)
        assert.are.equal(2, p.intel.central_basin.strength)
        -- gone: decays over INTEL_DECAY_FRAMES, then forgotten
        fe:setEnemies({})
        p = pic:refresh(160 + 2700)
        assert.is_true(math.abs(p.intel.central_basin.confidence - 0.5) < 0.01)
        p = pic:refresh(160 + 5400)
        assert.is_nil(p.intel.central_basin)
        -- blips: low confidence, unknown class, retracted each tick
        fe:setBlips({ { id = 11, x = 1500, z = 1500 } })
        p = pic:refresh(6000)
        assert.are.equal(0.5, p.intel.south_marsh.strength)
        assert.are.equal(0.35, p.intel.south_marsh.confidence)
        assert.are.equal(0.5, p.intel.south_marsh.byClass._blip)
        fe:setBlips({})
        p = pic:refresh(6010)
        assert.are.equal(0, p.intel.south_marsh.strength)
    end)

    it("summarises threat per own region and contact hops", function()
        fe:setOwnUnits({ { id = 1, defId = 101, x = 100, z = 100, health = 1.0 } })
        fe:setEnemies({ { id = 9, defId = 101, x = 1500, z = 500, health = 1.0 } })
        local p = Picture.new({}):refresh(150)
        assert.are.equal(1, p.contactHops)
        assert.are.equal(1.0, p.threat.north_ridge.adjacent)
        assert.are.equal(0, p.threat.north_ridge.inside)
        assert.are.equal(1, p.threat.north_ridge.hops)
        fe:setEnemies({ { id = 9, defId = 101, x = 200, z = 200, health = 1.0 } })
        p = Picture.new({}):refresh(160)
        assert.are.equal(0, p.contactHops)
        assert.are.equal(1.0, p.threat.north_ridge.inside)
    end)

    it("reads scenario slot parameters, profile hint and departure zone when published", function()
        fe:setRulesParam('team', 'ai_profile_7', 'skittish')
        fe:setRulesParam('team', 'ai_slate_kinds', 'garrison,raid')
        fe:setRulesParam('team', 'ai_slate_home', 'north_ridge')
        fe:setRulesParam('team', 'ai_slate_targets', 'central_basin')
        fe:setRulesParam('team', 'ms_departure_0_x', 0)
        fe:setRulesParam('team', 'ms_departure_0_z', 500)
        local p = Picture.new({}):refresh(150)
        assert.are.equal('skittish', p.profile)
        assert.are.same({ 'garrison', 'raid' }, p.script.kinds)
        assert.are.equal('north_ridge', p.script.home)
        assert.are.same({ x = 0, z = 500, radius = 700 }, p.departure)
        fe:setRulesParam('team', 'ai_profile_7', nil)
        fe:setRulesParam('team', 'ai_profile', 'stalwart')
        assert.are.equal('stalwart', Picture.profileHint(7))
    end)

    it("stays calm with no engine at all", function()
        FE.uninstall()
        local p = Picture.new({}):refresh(1)
        assert.are.same({}, p.regions); assert.are.same({}, p.ledger)
        assert.are.equal(-1, p.teamId)
        assert.is_nil(p.contactHops)
    end)
end)
