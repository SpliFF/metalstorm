/**
 * CegLoader — extract structured CEG (Custom Explosion Generator) defs
 * from the Lua explosion table the engine has already parsed.
 *
 * Spring authors particle effects as Lua tables under
 * `gamedata/explosions.lua` (which itself loads effects in ZK,
 * gamedata particles in classic Spring). The engine-side
 * `CExplosionGeneratorHandler` parses this whole tree on `Init()` and
 * keeps the root LuaTable around. We walk the root table once, extract
 * every CEG into a plain C++ struct, and ship the result as a
 * `GameCegDefs` FlatBuffer alongside the unit/weapon defs.
 *
 * The runtime CEG bytecode generated by `CCustomExplosionGenerator::Load`
 * is irrelevant here — we only care about the raw authored data so the
 * client can interpret it independently. (Headless servers don't even
 * have the visual particle classes the bytecode would feed into.)
 */
#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace SpringWeb { struct GameCegDefT; }

namespace CegLoader {

/// One key/value pair from the spawn-table's `properties` block.
/// Lua values are stringified — numbers, booleans, and lists all
/// arrive on the wire as strings the client decodes per-class.
struct CegProperty {
    std::string key;
    std::string value;
};

/// Visibility-flag bits matching the FlatBuffer schema.
constexpr uint8_t CEG_FLAG_GROUND     = 1u << 0;
constexpr uint8_t CEG_FLAG_AIR        = 1u << 1;
constexpr uint8_t CEG_FLAG_WATER      = 1u << 2;
constexpr uint8_t CEG_FLAG_UNIT       = 1u << 3;
constexpr uint8_t CEG_FLAG_UNDERWATER = 1u << 4;

/// One sub-emitter inside a CEG. Each fires `count` particles when
/// the spawn context (ground / air / water / unit / underwater)
/// matches `flags`. `flags == 0` is treated as "always emit".
struct CegSpawn {
    std::string spawnName;
    std::string className;
    int32_t     count = 1;
    uint8_t     flags = 0;
    std::vector<CegProperty> properties;
};

/// Spring's `CStandardGroundFlash` parameters. Authored at the
/// CEG-def top level as `groundflash = { ttl = …, … }`, NOT as a
/// spawn entry. Mirrors Recoil's `ExpGenParams.groundFlash` from
/// `Sim/Projectiles/ExplosionGenerator.cpp:1027-1038`. `ttl == 0`
/// means "no ground flash authored".
struct CegGroundFlash {
    int32_t ttl          = 0;
    float   circleAlpha  = 0.0f;
    float   flashSize    = 0.0f;
    float   flashAlpha   = 0.0f;
    float   circleGrowth = 0.0f;
    float   colorR       = 1.0f;
    float   colorG       = 1.0f;
    float   colorB       = 0.8f;
    uint8_t flags        = 0;
};

/// One CEG. The `tag` is the name weapon defs reference via
/// `cegTag` / `explosionGenerator` (lowercased on output).
struct CegDef {
    std::string tag;
    std::vector<CegSpawn> spawns;
    bool useDefaultExplosions = false;
    CegGroundFlash groundFlash; // `ttl == 0` = absent
};

/// Walk the engine's parsed explosion table and produce a flat list of
/// CEGs. Returns empty if the handler hasn't been initialised, the
/// table failed to parse, or it contains no entries. Idempotent —
/// safe to call once per game-server bake.
std::vector<CegDef> LoadAllCegDefs();

/// Build the framed `ServerMessage{GameCegDefs}` payload for shipping
/// to clients. Same envelope convention as BuildGameUnitDefs /
/// BuildGameWeaponDefs (see Protocol.h).
std::vector<uint8_t> BuildGameCegDefs(const std::vector<CegDef>& defs);

} // namespace CegLoader
